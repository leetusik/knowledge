#!/usr/bin/env python3
"""Generate web/src/lib/native/diagram-metrics.ts (P30.S17, `03-diagrams` build prompt, "Measuring on the server").

The diagram renderer measures text with the faces' own advance widths, never a browser. This script reads the vendored
variable woff2 files in web/public/fonts/, instances each at the weight the diagram uses, and writes the advance of every
codepoint the diagram can meet. Re-run it only when those font files change:

    uv run --with fonttools --with brotli python3 web/scripts/gen-diagram-metrics.py

Faces (all in units per em, so the TS multiplies by size / upm): Source Sans 3 at 400 and 600, JetBrains Mono 400,
Pretendard (the Hangul face) at 400 and 600. Kerning is ignored (a sum of advances is never narrower than the drawn text).
"""

from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "public" / "fonts"
OUT = ROOT / "src" / "lib" / "native" / "diagram-metrics.ts"

# The codepoints worth a table entry: Basic Latin to Latin Extended-B, spacing modifiers, general punctuation, arrows,
# a few math signs; Hangul Jamo and Compatibility Jamo (Pretendard). Anything else falls back (see diagram-text.ts).
RANGES = [
    (0x20, 0x24F),
    (0x2B0, 0x2FF),
    (0x2000, 0x206F),
    (0x20A0, 0x20CF),
    (0x2190, 0x21FF),
    (0x2200, 0x22FF),
    (0x25A0, 0x25FF),
]
JAMO = [(0x1100, 0x11FF), (0x3130, 0x318F)]
SYLLABLES = (0xAC00, 0xD7A3)

FACES = [
    ("sans400", "SourceSans3.woff2", 400, RANGES),
    ("sans600", "SourceSans3.woff2", 600, RANGES),
    ("mono400", "JetBrainsMono.woff2", 400, RANGES),
    ("ko400", "PretendardVariable.woff2", 400, RANGES + JAMO),
    ("ko600", "PretendardVariable.woff2", 600, RANGES + JAMO),
]


def face(file: str, wght: int, ranges):
    font = TTFont(FONTS / file)
    inst = instancer.instantiateVariableFont(font, {"wght": wght})
    cmap = inst.getBestCmap()
    hmtx = inst["hmtx"]
    upm = inst["head"].unitsPerEm
    pairs = []
    for cp in sorted(cmap):
        if any(lo <= cp <= hi for lo, hi in ranges):
            pairs.append((cp, hmtx[cmap[cp]][0]))
    syl = {hmtx[cmap[cp]][0] for cp in range(SYLLABLES[0], SYLLABLES[1] + 1) if cp in cmap}
    return upm, pairs, syl


def main() -> None:
    lines = [
        "// GENERATED by web/scripts/gen-diagram-metrics.py from public/fonts/*.woff2 (P30.S17). Not hand-edited.",
        "// Advance widths in font units per em: `cp:advance` pairs, space-separated. `syllable` is the width of every",
        "// Hangul syllable (U+AC00 to U+D7A3), which is the same for all 11,172 in Pretendard.",
        "",
        "export interface FaceMetrics {",
        "  upm: number;",
        "  table: string;",
        "  syllable: number | null;",
        "}",
        "",
        "export const FACES: Record<string, FaceMetrics> = {",
    ]
    for key, file, wght, ranges in FACES:
        upm, pairs, syl = face(file, wght, ranges)
        if len(syl) > 1:
            raise SystemExit(f"{key}: Hangul syllables differ in width: {sorted(syl)}")
        table = " ".join(f"{cp}:{w}" for cp, w in pairs)
        sy = next(iter(syl)) if syl else None
        lines.append(f'  "{key}": {{ upm: {upm}, syllable: {sy if sy is not None else "null"}, table: "{table}" }},')
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
